// Command modules validates the first-party module manifests and emits
// internal/modules/registry_gen.go. It fails when a manifest violates
// schemas/module/v1alpha1.schema.json or a settings schema does not compile
// as draft 2020-12 JSON Schema.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/santhosh-tekuri/jsonschema/v6"

	"github.com/jj-link/local-model-works/internal/modules"
)

const outPath = "internal/modules/registry_gen.go"

func main() {
	if len(os.Args) < 2 || os.Args[1] != "gen" {
		fmt.Fprintln(os.Stderr, "usage: modules gen")
		os.Exit(2)
	}
	if err := gen(); err != nil {
		fmt.Fprintln(os.Stderr, "modules:", err)
		os.Exit(1)
	}
}

func gen() error {
	abs, err := filepath.Abs("schemas/module/v1alpha1.schema.json")
	if err != nil {
		return err
	}
	id := "file://" + filepath.ToSlash(abs)
	compiler := jsonschema.NewCompiler()
	f, err := os.Open(abs)
	if err != nil {
		return err
	}
	defer f.Close()
	var doc any
	if err := json.NewDecoder(f).Decode(&doc); err != nil {
		return err
	}
	if err := compiler.AddResource(id, doc); err != nil {
		return err
	}
	schema, err := compiler.Compile(id)
	if err != nil {
		return fmt.Errorf("compile module schema: %w", err)
	}

	seen := map[string]bool{}
	for _, m := range modules.Manifests {
		data, err := json.Marshal(m)
		if err != nil {
			return fmt.Errorf("marshal %s: %w", m.ID, err)
		}
		var doc any
		if err := json.Unmarshal(data, &doc); err != nil {
			return err
		}
		if err := schema.Validate(doc); err != nil {
			return fmt.Errorf("module %s invalid: %v", m.ID, err)
		}
		if seen[m.ID] {
			return fmt.Errorf("duplicate module id %q", m.ID)
		}
		seen[m.ID] = true
		// The settings schema must itself be a valid draft 2020-12 schema.
		sc := jsonschema.NewCompiler()
		var sdoc any
		if err := json.Unmarshal(m.SettingsSchema, &sdoc); err != nil {
			return fmt.Errorf("module %s settings schema: %v", m.ID, err)
		}
		if err := sc.AddResource("settings://"+m.ID, sdoc); err != nil {
			return err
		}
		if _, err := sc.Compile("settings://" + m.ID); err != nil {
			return fmt.Errorf("module %s settings schema: %v", m.ID, err)
		}
	}

	list := append([]modules.Manifest(nil), modules.Manifests...)
	sort.Slice(list, func(i, j int) bool { return list[i].ID < list[j].ID })

	var b bytes.Buffer
	b.WriteString("// Code generated by \"go run ./internal/generate/modules gen\". DO NOT EDIT.\n")
	b.WriteString("// Source: internal/modules/manifests.go; schema: schemas/module/v1alpha1.schema.json.\n\n")
	b.WriteString("package modules\n\n")
	b.WriteString("import \"encoding/json\"\n\n")
	b.WriteString("// Registry is the frozen, ID-sorted set of first-party modules.\n")
	b.WriteString("var Registry = []Manifest{\n")
	for _, m := range list {
		b.WriteString("\t" + manifestLiteral(m) + ",\n")
	}
	b.WriteString("}\n")

	old, _ := os.ReadFile(outPath)
	if !bytes.Equal(old, b.Bytes()) {
		if err := os.WriteFile(outPath, b.Bytes(), 0o644); err != nil {
			return err
		}
		fmt.Println("wrote", outPath)
	} else {
		fmt.Println(outPath, "up to date")
	}
	return nil
}

// manifestLiteral renders a manifest as a Go composite literal so the
// generated registry is plain Go source.
func manifestLiteral(m modules.Manifest) string {
	var sb strings.Builder
	write := func(k string, v string) {
		sb.WriteString(", " + k + ": " + strconv.Quote(v))
	}
	writeList := func(k string, vals []string) {
		if len(vals) == 0 {
			return
		}
		quoted := make([]string, len(vals))
		for i, v := range vals {
			quoted[i] = strconv.Quote(v)
		}
		sb.WriteString(", " + k + ": []string{" + strings.Join(quoted, ", ") + "}")
	}
	sb.WriteString("{APIVersion: " + strconv.Quote(m.APIVersion) +
		", Kind: " + strconv.Quote(m.Kind) +
		", ID: " + strconv.Quote(m.ID) +
		", Title: " + strconv.Quote(m.Title) +
		", Route: " + strconv.Quote(m.Route) +
		", Nav: Nav{Label: " + strconv.Quote(m.Nav.Label) +
		", Order: " + strconv.Itoa(m.Nav.Order) +
		", Icon: " + strconv.Quote(m.Nav.Icon) + "}")
	if len(m.SettingsSchema) > 0 {
		sb.WriteString(", SettingsSchema: json.RawMessage(" + strconv.Quote(string(m.SettingsSchema)) + ")")
	}
	writeList("JobKinds", m.JobKinds)
	writeList("ArtifactKinds", m.ArtifactKinds)
	write("APIFragment", m.APIFragment)
	writeList("Capabilities", m.Capabilities)
	sb.WriteString("}")
	return sb.String()
}
